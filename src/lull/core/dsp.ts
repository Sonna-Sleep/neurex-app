/** Direct-form II transposed IIR filter (scipy.signal.lfilter, zi=0). */
function lfilter(b: number[], a: number[], x: number[], zi?: number[]): number[] {
  const n = Math.max(a.length, b.length);
  const bb = b.slice();
  const aa = a.slice();
  while (bb.length < n) bb.push(0);
  while (aa.length < n) aa.push(0);
  const a0 = aa[0];
  for (let i = 0; i < n; i++) {
    bb[i] /= a0;
    aa[i] /= a0;
  }
  const z = zi ? zi.slice() : new Array<number>(n - 1).fill(0);
  const y = new Array<number>(x.length);
  for (let m = 0; m < x.length; m++) {
    const xm = x[m];
    const ym = bb[0] * xm + z[0];
    y[m] = ym;
    for (let i = 1; i < n - 1; i++) {
      z[i - 1] = bb[i] * xm + z[i] - aa[i] * ym;
    }
    z[n - 2] = bb[n - 1] * xm - aa[n - 1] * ym;
  }
  return y;
}

/** Compute lfilter_zi: steady-state initial conditions (scipy.signal.lfilter_zi). */
function lfilterZi(b: number[], a: number[]): number[] {
  const n = Math.max(a.length, b.length);
  const bb = b.slice();
  const aa = a.slice();
  while (bb.length < n) bb.push(0);
  while (aa.length < n) aa.push(0);
  const a0 = aa[0];
  const bn = bb.map((v) => v / a0);
  const an = aa.map((v) => v / a0);
  const order = n - 1;
  // scipy.signal.lfilter_zi: solve (I - A) zi = B, where A is the companion
  // matrix of the (normalized) denominator and B[i] = bn[i+1] - an[i+1]*bn[0].
  const B: number[] = [];
  for (let i = 0; i < order; i++) B.push(bn[i + 1] - an[i + 1] * bn[0]);
  // Companion matrix C: first row = -an[1..], identity sub-diagonal below.
  const C: number[][] = [];
  for (let i = 0; i < order; i++) C.push(new Array<number>(order).fill(0));
  for (let j = 0; j < order; j++) C[0][j] = -an[j + 1];
  for (let i = 1; i < order; i++) C[i][i - 1] = 1;
  // Build (I - A) with A = C^T, then solve via Gaussian elimination.
  const A: number[][] = [];
  for (let i = 0; i < order; i++) {
    A.push(new Array<number>(order).fill(0));
    for (let j = 0; j < order; j++) {
      A[i][j] = (i === j ? 1 : 0) - C[j][i];
    }
  }
  return solveLinear(A, B);
}

/** Gaussian elimination with partial pivoting: solve A x = b. */
function solveLinear(Ain: number[][], bin: number[]): number[] {
  const n = bin.length;
  const A = Ain.map((row) => row.slice());
  const b = bin.slice();
  for (let col = 0; col < n; col++) {
    let piv = col;
    for (let r = col + 1; r < n; r++) {
      if (Math.abs(A[r][col]) > Math.abs(A[piv][col])) piv = r;
    }
    [A[col], A[piv]] = [A[piv], A[col]];
    [b[col], b[piv]] = [b[piv], b[col]];
    const d = A[col][col];
    if (Math.abs(d) < 1e-300) continue;
    for (let r = 0; r < n; r++) {
      if (r === col) continue;
      const f = A[r][col] / d;
      for (let c = col; c < n; c++) A[r][c] -= f * A[col][c];
      b[r] -= f * b[col];
    }
  }
  const x = new Array<number>(n);
  for (let i = 0; i < n; i++) x[i] = b[i] / A[i][i];
  return x;
}

/**
 * scipy.signal.filtfilt with default 'pad' method and odd extension.
 * padlen defaults to 3 * max(len(a), len(b)).
 */
export function filtfilt(b: number[], a: number[], x: number[]): number[] {
  // scipy default: padlen = 3 * max(len(a), len(b)).
  const ntaps = Math.max(a.length, b.length);
  const edge = 3 * ntaps;
  if (x.length <= edge) {
    // not enough data to pad; fall back to plain forward-backward without padding
    const zi0 = lfilterZi(b, a);
    const f = lfilter(b, a, x, zi0.map((v) => v * x[0]));
    const rev = f.slice().reverse();
    const zi1 = lfilterZi(b, a);
    const bk = lfilter(b, a, rev, zi1.map((v) => v * rev[0]));
    return bk.reverse();
  }
  // odd extension on both ends
  const ext: number[] = [];
  for (let i = edge; i >= 1; i--) ext.push(2 * x[0] - x[i]);
  for (let i = 0; i < x.length; i++) ext.push(x[i]);
  for (let i = x.length - 2; i >= x.length - 1 - edge; i--) ext.push(2 * x[x.length - 1] - x[i]);

  const zi = lfilterZi(b, a);
  // forward
  const fwd = lfilter(b, a, ext, zi.map((v) => v * ext[0]));
  // backward
  const rev = fwd.slice().reverse();
  const bwd = lfilter(b, a, rev, zi.map((v) => v * rev[0]));
  const y = bwd.reverse();
  // trim the extension
  return y.slice(edge, edge + x.length);
}

