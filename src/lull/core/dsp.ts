// Butterworth design (matches scipy.signal.butter, output as second-order
// sections) + zero-phase forward/backward filtering (matches filtfilt).
// ---------------------------------------------------------------------------

interface Complex {
  re: number;
  im: number;
}

const cMul = (a: Complex, b: Complex): Complex => ({
  re: a.re * b.re - a.im * b.im,
  im: a.re * b.im + a.im * b.re,
});
const cAdd = (a: Complex, b: Complex): Complex => ({ re: a.re + b.re, im: a.im + b.im });
const cSub = (a: Complex, b: Complex): Complex => ({ re: a.re - b.re, im: a.im - b.im });
const cDiv = (a: Complex, b: Complex): Complex => {
  const d = b.re * b.re + b.im * b.im;
  return { re: (a.re * b.re + a.im * b.im) / d, im: (a.im * b.re - a.re * b.im) / d };
};

/** Expand monic polynomial from its complex roots: returns real coeffs (highest first). */
function polyFromRoots(roots: Complex[]): number[] {
  let coeffs: Complex[] = [{ re: 1, im: 0 }];
  for (const r of roots) {
    const next: Complex[] = new Array(coeffs.length + 1)
      .fill(0)
      .map(() => ({ re: 0, im: 0 }));
    for (let i = 0; i < coeffs.length; i++) {
      next[i] = cAdd(next[i], coeffs[i]); // * 1 (z term)
      next[i + 1] = cSub(next[i + 1], cMul(coeffs[i], r)); // * (-root)
    }
    coeffs = next;
  }
  return coeffs.map((c) => c.re);
}

interface TF {
  b: number[];
  a: number[];
}

/**
 * Design a digital Butterworth filter (lowpass/highpass/bandpass) exactly as
 * scipy.signal.butter does: analog prototype zpk -> frequency transform ->
 * bilinear transform. Wn entries are normalized to Nyquist (0..1). Returns
 * transfer-function coeffs {b, a}.
 */
export function butter(
  order: number,
  Wn: number | [number, number],
  btype: 'low' | 'high' | 'band'
): TF {
  // --- analog lowpass prototype: poles on unit circle, no finite zeros ---
  const protoPoles: Complex[] = [];
  for (let k = 0; k < order; k++) {
    const theta = (Math.PI * (2 * k + 1)) / (2 * order) + Math.PI / 2;
    protoPoles.push({ re: Math.cos(theta), im: Math.sin(theta) });
  }
  let z: Complex[] = [];
  let p: Complex[] = protoPoles.slice();
  let k = 1; // prototype gain (product of -poles for butterworth == 1)

  const fs = 2.0; // bilinear pre-warp uses fs=2 (scipy convention with Wn pre-warped)

  if (btype === 'low' || btype === 'high') {
    const wn = Wn as number;
    const warped = 2 * fs * Math.tan((Math.PI * wn) / fs);
    if (btype === 'low') {
      // lp2lp: s -> s/warped
      const degree = p.length - z.length;
      z = z.map((zz) => ({ re: zz.re * warped, im: zz.im * warped }));
      p = p.map((pp) => ({ re: pp.re * warped, im: pp.im * warped }));
      k = k * Math.pow(warped, degree);
    } else {
      // lp2hp: s -> warped/s
      const degree = p.length - z.length;
      const newZ: Complex[] = z.map((zz) => cDiv({ re: warped, im: 0 }, zz));
      const newP: Complex[] = p.map((pp) => cDiv({ re: warped, im: 0 }, pp));
      // gain: k * real(prod(-z)/prod(-p))
      let num: Complex = { re: 1, im: 0 };
      for (const zz of z) num = cMul(num, { re: -zz.re, im: -zz.im });
      let den: Complex = { re: 1, im: 0 };
      for (const pp of p) den = cMul(den, { re: -pp.re, im: -pp.im });
      k = k * cDiv(num, den).re;
      // add zeros at origin to bring degree up
      for (let i = 0; i < degree; i++) newZ.push({ re: 0, im: 0 });
      z = newZ;
      p = newP;
    }
  } else {
    // bandpass
    const [lo, hi] = Wn as [number, number];
    const warpedLo = 2 * fs * Math.tan((Math.PI * lo) / fs);
    const warpedHi = 2 * fs * Math.tan((Math.PI * hi) / fs);
    const bw = warpedHi - warpedLo;
    const wo = Math.sqrt(warpedLo * warpedHi);
    // lp2bp: s -> (s^2 + wo^2)/(bw*s)
    const degree = p.length - z.length;
    // scale poles/zeros: p_lp * bw/2
    const pScaled = p.map((pp) => ({ re: (pp.re * bw) / 2, im: (pp.im * bw) / 2 }));
    const newP: Complex[] = [];
    for (const ps of pScaled) {
      // p +/- sqrt(p^2 - wo^2)
      const p2: Complex = cSub(cMul(ps, ps), { re: wo * wo, im: 0 });
      const root = csqrt(p2);
      newP.push(cAdd(ps, root));
      newP.push(cSub(ps, root));
    }
    // zeros: existing scaled (none) -> map, then add `degree` zeros at origin
    const newZ: Complex[] = [];
    for (let i = 0; i < degree; i++) newZ.push({ re: 0, im: 0 });
    // gain: k * bw^degree
    k = k * Math.pow(bw, degree);
    z = newZ;
    p = newP;
  }

  // --- bilinear transform: s -> 2*fs*(z-1)/(z+1) ---
  const fs2 = 2 * fs;
  const zDigital: Complex[] = [];
  const pDigital: Complex[] = [];
  // bilinear: z_d = (fs2 + s)/(fs2 - s)
  for (const s of z) {
    zDigital.push(cDiv(cAdd({ re: fs2, im: 0 }, s), cSub({ re: fs2, im: 0 }, s)));
  }
  for (const s of p) {
    pDigital.push(cDiv(cAdd({ re: fs2, im: 0 }, s), cSub({ re: fs2, im: 0 }, s)));
  }
  // gain factor: k * real( prod(fs2 - z_s) / prod(fs2 - p_s) )
  let numG: Complex = { re: 1, im: 0 };
  for (const s of z) numG = cMul(numG, cSub({ re: fs2, im: 0 }, s));
  let denG: Complex = { re: 1, im: 0 };
  for (const s of p) denG = cMul(denG, cSub({ re: fs2, im: 0 }, s));
  let kd = k * cDiv(numG, denG).re;
  // zeros gained by bilinear: zeros at -1 to match pole count
  const fill = pDigital.length - zDigital.length;
  for (let i = 0; i < fill; i++) zDigital.push({ re: -1, im: 0 });

  // --- assemble transfer function ---
  const bComplex = polyFromRoots(zDigital);
  const aComplex = polyFromRoots(pDigital);
  const b = bComplex.map((c) => c * kd);
  const a = aComplex;
  return { b, a };
}

function csqrt(c: Complex): Complex {
  const r = Math.hypot(c.re, c.im);
  const re = Math.sqrt((r + c.re) / 2);
  let im = Math.sqrt((r - c.re) / 2);
  if (c.im < 0) im = -im;
  return { re, im };
}

/**
 * scipy.signal.iirnotch(w0, Q, fs): second-order IIR notch.
 * Returns {b, a}. w0 = mains_hz, fs = sampling rate.
 */
export function iirnotch(w0Hz: number, Q: number, fs: number): TF {
  const w0 = w0Hz / (fs / 2.0); // normalized to Nyquist (0..1)
  const bw = w0 / Q;
  const wpi = w0 * Math.PI;
  const bwpi = bw * Math.PI;
  const gb = 1 / Math.SQRT2;
  const beta = (Math.sqrt(1.0 - gb * gb) / gb) * Math.tan(bwpi / 2.0);
  const gain = 1.0 / (1.0 + beta);
  const b = [gain, -2.0 * Math.cos(wpi) * gain, gain];
  const a = [1.0, -2.0 * Math.cos(wpi) * gain, 2.0 * gain - 1.0];
  return { b, a };
}

