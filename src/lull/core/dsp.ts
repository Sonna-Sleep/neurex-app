/** Band-pass with detrend then zero-phase filtfilt. Mirrors `_bandpass`. */
export function bandpass(
  x: number[],
  fs: number,
  lo: number,
  hi: number,
  order: number
): number[] {
  const xd = detrendConstant(x);
  const nyq = fs / 2.0;
  const loN = Math.max(lo / nyq, 1e-4);
  const hiN = Math.min(hi / nyq, 0.99);
  const { b, a } = butter(order, [loN, hiN], 'band');
  return filtfilt(b, a, xd);
}

/** Notch at mains; skip if mains >= Nyquist. Mirrors `_notch`. */
export function notch(x: number[], fs: number, mainsHz: number, q: number): number[] {
  if (mainsHz <= 0 || mainsHz >= fs / 2.0) return x.slice();
  const { b, a } = iirnotch(mainsHz, q, fs);
  return filtfilt(b, a, x);
}

/**
 * Welch PSD with Hann window, 50% overlap, nperseg=min(len, max(fs*seg, min)).
 * Mirrors `_welch_psd` (scipy.signal.welch with detrend='constant').
 * Returns frequency bins and one-sided PSD.
 */
export function welchPsd(
  x: number[],
  fs: number,
  segSec: number,
  minSamples = 32
): { f: number[]; pxx: number[] } {
  const nperseg = Math.floor(Math.min(x.length, Math.max(fs * segSec, minSamples)));
  const noverlap = Math.floor(nperseg / 2); // scipy default for welch
  const step = nperseg - noverlap;

  // Hann window (scipy 'hann', sym=False -> periodic): w[n]=0.5-0.5cos(2*pi*n/M)
  const win = new Array<number>(nperseg);
  for (let i = 0; i < nperseg; i++) {
    win[i] = 0.5 - 0.5 * Math.cos((2 * Math.PI * i) / nperseg);
  }
  let winSqSum = 0;
  for (let i = 0; i < nperseg; i++) winSqSum += win[i] * win[i];
  const scale = 1.0 / (fs * winSqSum);

  const nfreq = Math.floor(nperseg / 2) + 1;
  const psdAccum = new Array<number>(nfreq).fill(0);
  let nSeg = 0;

  for (let start = 0; start + nperseg <= x.length; start += step) {
    const seg = x.slice(start, start + nperseg);
    // detrend constant
    const m = mean(seg);
    for (let i = 0; i < nperseg; i++) seg[i] = (seg[i] - m) * win[i];
    const { re, im } = dft(seg);
    for (let k = 0; k < nfreq; k++) {
      let p = (re[k] * re[k] + im[k] * im[k]) * scale;
      // one-sided: double all but DC and Nyquist
      if (k !== 0 && !(nperseg % 2 === 0 && k === nfreq - 1)) p *= 2;
      psdAccum[k] += p;
    }
    nSeg++;
  }
  if (nSeg === 0) {
    // window shorter than nperseg should not happen given the floor, but guard
    return { f: [0], pxx: [0] };
  }
  const pxx = psdAccum.map((v) => v / nSeg);
  const f = new Array<number>(nfreq);
  for (let k = 0; k < nfreq; k++) f[k] = (k * fs) / nperseg;
  return { f, pxx };
}

/** Trapezoidal band power over [lo, hi). Mirrors `_bandpower`. */
export function bandpower(f: number[], pxx: number[], lo: number, hi: number): number {
  const xs: number[] = [];
  const ys: number[] = [];
  for (let i = 0; i < f.length; i++) {
    if (f[i] >= lo && f[i] < hi) {
      xs.push(f[i]);
      ys.push(pxx[i]);
    }
  }
  if (xs.length === 0) return 0.0;
  // np.trapezoid(y, x)
  let area = 0;
  for (let i = 1; i < xs.length; i++) {
    area += ((ys[i] + ys[i - 1]) / 2) * (xs[i] - xs[i - 1]);
  }
  return area;
}

/** Spectral edge frequency at cumulative `pct` over [lo, hi]. Mirrors `_sef`. */
export function sef(
  f: number[],
  pxx: number[],
  lo: number,
  hi: number,
  pct: number
): number {
  const f2: number[] = [];
  const p2: number[] = [];
  for (let i = 0; i < f.length; i++) {
    if (f[i] >= lo && f[i] <= hi) {
      f2.push(f[i]);
      p2.push(pxx[i]);
    }
  }
  if (f2.length === 0) return 0.0;
  let total = 0;
  for (const v of p2) total += v;
  if (total <= 0) return 0.0;
  const c = new Array<number>(p2.length);
  let run = 0;
  for (let i = 0; i < p2.length; i++) {
    run += p2[i];
    c[i] = run / total;
  }
  // np.searchsorted(c, pct) -> first index where c[idx] >= pct
  let k = c.length;
  for (let i = 0; i < c.length; i++) {
    if (c[i] >= pct) {
      k = i;
      break;
    }
  }
  return f2[Math.min(k, f2.length - 1)];
}

/** High-pass RMS at cutoff `hz`; 0 if input is all-zero. Mirrors `_highpass_rms`. */
export function highpassRms(x: number[], fs: number, hz: number, order: number): number {
  let allZero = true;
  for (const v of x) {
    if (Math.abs(v) > 1e-12) {
      allZero = false;
      break;
    }
  }
  if (allZero) return 0.0;
  const m = mean(x);
  const xc = x.map((v) => v - m);
  const wn = Math.min(hz / (fs / 2.0), 0.99);
  const { b, a } = butter(order, wn, 'high');
  const y = filtfilt(b, a, xc);
  let ss = 0;
  for (const v of y) ss += v * v;
  return Math.sqrt(ss / y.length);
}
