/**
 * Lull DSP core — scipy-faithful signal processing for the drowsiness pipeline.
 *
 * PURE: no I/O, no platform deps, no wall-clock. Every numeric routine here is a
 * direct port of the operation used by the Phase-1 Python source of truth
 * (`tools/lull/sleepiness.py`, which relies on scipy.signal). The golden-vector
 * contract (`__tests__/golden/lull_vectors.json`) is the acceptance test.
 *
 * Why hand-rolled instead of leaning on fili's high-level helpers:
 *   - scipy.signal.butter designs an analog Butterworth prototype and maps it to
 *     digital via the bilinear transform with frequency pre-warping. fili's
 *     `bandpass` uses a center-frequency + bandwidth cascade with a different
 *     normalization, so its coefficients do NOT match scipy's. We reproduce
 *     scipy's exact design (zpk -> bilinear -> SOS -> filtfilt) so the golden
 *     vectors generated by scipy reproduce here within tolerance.
 *   - scipy.signal.welch uses an arbitrary nperseg DFT (no power-of-2 padding).
 *     fili's radix-2 FFT can't size to nperseg=1000, so we use a Bluestein FFT
 *     for the exact-length periodogram.
 */

// ---------------------------------------------------------------------------
// Complex FFT (Bluestein / chirp-z) — supports arbitrary length N.
// ---------------------------------------------------------------------------

/** In-place radix-2 Cooley–Tukey FFT. len(re)===len(im)===power of two. */
function fftRadix2(re: number[], im: number[]): void {
  const n = re.length;
  if (n <= 1) return;
  // bit-reversal permutation
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) {
      [re[i], re[j]] = [re[j], re[i]];
      [im[i], im[j]] = [im[j], im[i]];
    }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = (-2 * Math.PI) / len;
    const wr = Math.cos(ang);
    const wi = Math.sin(ang);
    for (let i = 0; i < n; i += len) {
      let curR = 1;
      let curI = 0;
      for (let k = 0; k < len / 2; k++) {
        const aR = re[i + k];
        const aI = im[i + k];
        const bR = re[i + k + len / 2] * curR - im[i + k + len / 2] * curI;
        const bI = re[i + k + len / 2] * curI + im[i + k + len / 2] * curR;
        re[i + k] = aR + bR;
        im[i + k] = aI + bI;
        re[i + k + len / 2] = aR - bR;
        im[i + k + len / 2] = aI - bI;
        const nextR = curR * wr - curI * wi;
        curI = curR * wi + curI * wr;
        curR = nextR;
      }
    }
  }
}

/**
 * Forward DFT of arbitrary length via Bluestein's algorithm.
 * Returns { re, im } of length n (full complex spectrum).
 */
export function dft(real: number[]): { re: number[]; im: number[] } {
  const n = real.length;
  // pick FFT size m = next power of two >= 2n-1
  let m = 1;
  while (m < 2 * n - 1) m <<= 1;

  // chirp: w_k = exp(-i*pi*k^2/n)
  const cosT = new Array<number>(n);
  const sinT = new Array<number>(n);
  for (let k = 0; k < n; k++) {
    // (k*k mod 2n) keeps the argument small for numerical stability
    const j = (k * k) % (2 * n);
    const ang = (Math.PI * j) / n;
    cosT[k] = Math.cos(ang);
    sinT[k] = Math.sin(ang);
  }

  const aR = new Array<number>(m).fill(0);
  const aI = new Array<number>(m).fill(0);
  for (let k = 0; k < n; k++) {
    aR[k] = real[k] * cosT[k];
    aI[k] = -real[k] * sinT[k];
  }

  const bR = new Array<number>(m).fill(0);
  const bI = new Array<number>(m).fill(0);
  bR[0] = cosT[0];
  bI[0] = sinT[0];
  for (let k = 1; k < n; k++) {
    bR[k] = bR[m - k] = cosT[k];
    bI[k] = bI[m - k] = sinT[k];
  }

  fftRadix2(aR, aI);
  fftRadix2(bR, bI);
  for (let k = 0; k < m; k++) {
    const xr = aR[k] * bR[k] - aI[k] * bI[k];
    const xi = aR[k] * bI[k] + aI[k] * bR[k];
    aR[k] = xr;
    aI[k] = xi;
  }
  // inverse FFT (conjugate trick)
  for (let k = 0; k < m; k++) aI[k] = -aI[k];
  fftRadix2(aR, aI);
  for (let k = 0; k < m; k++) {
    aR[k] = aR[k] / m;
    aI[k] = -aI[k] / m;
  }

  const re = new Array<number>(n);
  const im = new Array<number>(n);
  for (let k = 0; k < n; k++) {
    re[k] = aR[k] * cosT[k] + aI[k] * sinT[k];
    im[k] = -aR[k] * sinT[k] + aI[k] * cosT[k];
  }
  return { re, im };
}

// ---------------------------------------------------------------------------
// Helpers: detrend, mean, RMS.
// ---------------------------------------------------------------------------

export function mean(x: number[]): number {
  let s = 0;
  for (let i = 0; i < x.length; i++) s += x[i];
  return s / x.length;
}

/** scipy.signal.detrend(x, type='constant'): subtract the mean. */
export function detrendConstant(x: number[]): number[] {
  const m = mean(x);
  const out = new Array<number>(x.length);
  for (let i = 0; i < x.length; i++) out[i] = x[i] - m;
  return out;
}

